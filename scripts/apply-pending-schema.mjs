/**
 * Applies pending Supabase migrations (0005+) to the linked dev project.
 *
 * Usage:
 *   $env:SUPABASE_DB_PASSWORD = "your-db-password"
 *   npm run db:patch
 *
 * Find the password in Supabase Dashboard → Project Settings → Database.
 * Without the password, writes combined SQL to supabase/_pending_migrations.sql
 * for paste into the SQL Editor (does not flood the terminal).
 */

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(root, 'supabase', 'migrations');
const outputFile = join(root, 'supabase', '_pending_migrations.sql');

/** Migrations safe to re-apply on dev (0001–0004 assumed already applied). */
const PENDING_PREFIXES = ['0005_', '0006_', '0007_', '0008_', '0009_', '0010_', '0011_', '0012_'];

function loadEnvFiles() {
  for (const name of ['.env', '.env.local']) {
    const path = join(root, name);
    if (!existsSync(path)) continue;
    const text = readFileSync(path, 'utf8');
    for (const line of text.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eq = trimmed.indexOf('=');
      if (eq <= 0) continue;
      const key = trimmed.slice(0, eq).trim();
      let value = trimmed.slice(eq + 1).trim();
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }
      if (process.env[key] == null) process.env[key] = value;
    }
  }
}

function loadPendingMigrations() {
  const files = readdirSync(migrationsDir)
    .filter((name) => PENDING_PREFIXES.some((prefix) => name.startsWith(prefix)))
    .sort();

  return files.map((name) => ({
    name,
    sql: readFileSync(join(migrationsDir, name), 'utf8'),
  }));
}

function projectRefFromEnv() {
  const url = process.env.EXPO_PUBLIC_SUPABASE_URL ?? process.env.SUPABASE_URL;
  if (!url) return undefined;
  try {
    return new URL(url).hostname.split('.')[0];
  } catch {
    return undefined;
  }
}

loadEnvFiles();

const migrations = loadPendingMigrations();
const combinedSql = [
  '-- Auto-generated by npm run db:patch',
  '-- Run in Supabase Dashboard → SQL Editor (in file order)',
  '',
  ...migrations.flatMap((m) => [`-- ${m.name}`, m.sql, '']),
].join('\n');

writeFileSync(outputFile, combinedSql, 'utf8');

const password = process.env.SUPABASE_DB_PASSWORD;
const projectRef = projectRefFromEnv() ?? 'YOUR_PROJECT_REF';

if (!password) {
  console.log('Missing SUPABASE_DB_PASSWORD — SQL written to file instead.\n');
  console.log(`  ${outputFile}\n`);
  console.log('Migrations included:');
  for (const m of migrations) console.log(`  • ${m.name}`);
  console.log('\nOption A — SQL Editor:');
  console.log(`  https://supabase.com/dashboard/project/${projectRef}/sql/new`);
  console.log('  Open the file above, copy all, paste, and Run.\n');
  console.log('Option B — automatic apply:');
  console.log('  $env:SUPABASE_DB_PASSWORD = "your-db-password"');
  console.log('  npm run db:patch');
  process.exit(1);
}

const connectionString =
  process.env.SUPABASE_DB_URL ??
  `postgresql://postgres:${encodeURIComponent(password)}@db.${projectRef}.supabase.co:5432/postgres`;

const { default: pg } = await import('pg');
const client = new pg.Client({
  connectionString,
  ssl: { rejectUnauthorized: false },
});

try {
  await client.connect();
  for (const migration of migrations) {
    console.log(`Applying ${migration.name}…`);
    await client.query(migration.sql);
  }
  await client.query("notify pgrst, 'reload schema';");
  console.log(`Applied ${migrations.length} migration(s) successfully.`);
} catch (error) {
  console.error('Failed to apply schema migrations:', error);
  console.error(`\nFallback: paste ${outputFile} into the Supabase SQL Editor.`);
  process.exit(1);
} finally {
  await client.end();
}
